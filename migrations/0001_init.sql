-- Гэр360: PostgreSQL (Neon) схем. `npm run db:migrate` дарааллаар нь нэг удаа ажиллуулна.

-- Админ, агент (нийтийн бүртгэлгүй; агентыг админ үүсгэнэ)
create table users (
  id text primary key,
  name text not null,
  email text not null unique,             -- нэвтрэх нэр, жижиг үсгээр
  phone text not null default '',         -- зар дээрх холбоо барих утас
  role text not null check (role in ('admin', 'agent')),
  active boolean not null default true,
  must_change_password boolean not null default false,
  password text not null,                 -- pbkdf2-sha256$<iter>$<salt>$<hash>
  created_at timestamptz not null default now()
);

-- Нэвтрэлт: cookie-д санамсаргүй токен, энд зөвхөн түүний SHA-256 хэш
create table sessions (
  token_hash text primary key,
  user_id text not null references users (id) on delete cascade,
  created_at timestamptz not null default now(),
  expires_at timestamptz not null
);
create index sessions_user_idx on sessions (user_id);

-- Буруу нэвтрэх оролдлого (бүх Worker instance-д нийтлэг хурдны хязгаар)
create table login_attempts (
  key text not null,
  at timestamptz not null default now()
);
create index login_attempts_key_idx on login_attempts (key, at);

-- Зар: шүүлтүүрт хэрэгтэй талбарууд багана, бусад нь `data` (jsonb). Нийтэд "L" || no хэлбэрээр.
create table listings (
  no integer generated by default as identity (start with 100001) primary key,
  owner_id text references users (id) on delete set null,
  owner_token text,                       -- хуучин (нэвтрэлтгүй үеийн) зарын түлхүүр
  owner_phone text not null,
  status text not null,
  deal_type text not null,
  category text not null,
  district text not null,
  price double precision not null,
  price_per_m2 double precision,
  area double precision,
  rooms integer,
  floor integer,
  building_floors integer,
  year_in_use integer,
  garage boolean not null default false,
  leasing boolean not null default false,
  has_tour boolean not null default false,
  seller_type text not null,
  placement text not null default 'free',
  placement_until timestamptz,
  created_at timestamptz not null default now(),
  expires_at timestamptz not null,
  views integer not null default 0,
  search_text text not null default '',   -- JS-ээр жижигрүүлсэн гарчиг, тайлбар, хаяг
  data jsonb not null default '{}'
);
create index listings_browse_idx on listings (status, deal_type, category);
create index listings_district_idx on listings (district);
create index listings_created_idx on listings (created_at desc);
create index listings_price_idx on listings (price);
create index listings_owner_idx on listings (owner_id);

-- Зарын тухай мэдээлэл (гомдол)
create table reports (
  id text primary key,
  listing_id text not null,               -- "L100001"
  reason text not null,
  note text not null default '',
  created_at timestamptz not null default now()
);
create index reports_listing_idx on reports (listing_id);
